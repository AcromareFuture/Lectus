CREATE TABLE lc_community_post (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 author_id BIGINT, official BOOLEAN NOT NULL DEFAULT FALSE,
 title VARCHAR(80) NOT NULL, body VARCHAR(2000) NOT NULL DEFAULT '',
 topic VARCHAR(30) NOT NULL, kind VARCHAR(8) NOT NULL,
 request_key VARCHAR(64), deleted BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(author_id,request_key)
);
CREATE TABLE lc_community_media (
 id VARCHAR(32) PRIMARY KEY, owner_id BIGINT, post_id BIGINT REFERENCES lc_community_post(id),
 kind VARCHAR(8) NOT NULL, filename VARCHAR(80), external_url VARCHAR(300),
 content_type VARCHAR(40) NOT NULL, width INT NOT NULL, height INT NOT NULL,
 duration_seconds INT NOT NULL DEFAULT 0, sort_order INT NOT NULL DEFAULT 0,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE lc_community_reaction (
 member_id BIGINT NOT NULL, post_id BIGINT NOT NULL REFERENCES lc_community_post(id),
 kind VARCHAR(8) NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(member_id,post_id,kind)
);
CREATE TABLE lc_community_follow (
 member_id BIGINT NOT NULL, author_id BIGINT NOT NULL,
 PRIMARY KEY(member_id,author_id), CHECK(member_id<>author_id)
);
CREATE TABLE lc_community_comment (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 post_id BIGINT NOT NULL REFERENCES lc_community_post(id), author_id BIGINT NOT NULL,
 body VARCHAR(500) NOT NULL, request_key VARCHAR(64) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, UNIQUE(author_id,request_key)
);
CREATE INDEX lc_community_feed ON lc_community_post(deleted,id DESC);
CREATE INDEX lc_community_author ON lc_community_post(author_id,id DESC);
CREATE INDEX lc_community_media_post ON lc_community_media(post_id,sort_order);
CREATE INDEX lc_community_comments ON lc_community_comment(post_id,id);
