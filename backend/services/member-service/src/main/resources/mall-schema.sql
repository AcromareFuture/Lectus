CREATE TABLE IF NOT EXISTS lc_merchant (
 id VARCHAR(40) PRIMARY KEY, name VARCHAR(100) NOT NULL, type VARCHAR(10) NOT NULL,
 category VARCHAR(40) NOT NULL, company VARCHAR(150) NOT NULL, contact VARCHAR(100) NOT NULL,
 submitted VARCHAR(20) NOT NULL, status VARCHAR(20) NOT NULL, reason VARCHAR(200) DEFAULT ''
);
CREATE TABLE IF NOT EXISTS lc_staff (
 username VARCHAR(60) PRIMARY KEY, password_hash VARCHAR(100) NOT NULL,
 role VARCHAR(20) NOT NULL, merchant_id VARCHAR(40) REFERENCES lc_merchant(id)
);
CREATE TABLE IF NOT EXISTS lc_staff_session (
 token_hash CHAR(64) PRIMARY KEY, username VARCHAR(60) NOT NULL REFERENCES lc_staff(username), expires_at TIMESTAMP NOT NULL
);
CREATE TABLE IF NOT EXISTS lc_product (
 id VARCHAR(40) PRIMARY KEY, merchant_id VARCHAR(40) NOT NULL REFERENCES lc_merchant(id),
 name VARCHAR(300) NOT NULL, spec VARCHAR(150) NOT NULL, category VARCHAR(40) NOT NULL,
 image VARCHAR(150) NOT NULL, price_fen BIGINT NOT NULL CHECK(price_fen>0), stock INT NOT NULL CHECK(stock>=0),
 status VARCHAR(20) NOT NULL, submitted VARCHAR(20) NOT NULL, reason VARCHAR(200) DEFAULT ''
);
CREATE TABLE IF NOT EXISTS lc_order (
 id VARCHAR(40) PRIMARY KEY, member_id BIGINT NOT NULL REFERENCES v_member(member_id),
 request_key VARCHAR(64) NOT NULL, product_id VARCHAR(40) NOT NULL REFERENCES lc_product(id),
 merchant_id VARCHAR(40) NOT NULL REFERENCES lc_merchant(id), product_name VARCHAR(300) NOT NULL,
 spec VARCHAR(150) NOT NULL, image VARCHAR(150) NOT NULL, amount_fen BIGINT NOT NULL,
 quantity INT NOT NULL CHECK(quantity>0), status VARCHAR(20) NOT NULL, created_at TIMESTAMP NOT NULL,
 paid_at TIMESTAMP, carrier VARCHAR(40) DEFAULT '', tracking VARCHAR(60) DEFAULT '',
 recipient VARCHAR(40) NOT NULL, phone VARCHAR(20) NOT NULL, address VARCHAR(250) NOT NULL,
 UNIQUE(member_id,request_key)
);
CREATE INDEX IF NOT EXISTS lc_order_merchant_time ON lc_order(merchant_id,created_at);
ALTER TABLE lc_product ADD COLUMN IF NOT EXISTS source_product_id VARCHAR(32);
CREATE INDEX IF NOT EXISTS lc_product_source ON lc_product(source_product_id);
CREATE TABLE IF NOT EXISTS lc_aftersale (
 id VARCHAR(40) PRIMARY KEY, order_id VARCHAR(40) NOT NULL UNIQUE REFERENCES lc_order(id),
 reason VARCHAR(200) NOT NULL, status VARCHAR(20) NOT NULL, result VARCHAR(200) DEFAULT '',
 previous_status VARCHAR(20) NOT NULL, created_at TIMESTAMP NOT NULL
);
CREATE TABLE IF NOT EXISTS lc_audit (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, created_at TIMESTAMP NOT NULL,
 actor VARCHAR(60) NOT NULL, action VARCHAR(60) NOT NULL, target VARCHAR(60) NOT NULL, detail VARCHAR(250) NOT NULL
);

