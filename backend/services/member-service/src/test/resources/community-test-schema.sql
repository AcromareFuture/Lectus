CREATE TABLE IF NOT EXISTS v_store (
 store_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(80) NOT NULL,
 address VARCHAR(300) NOT NULL, hours VARCHAR(100) NOT NULL, phone VARCHAR(30),
 description VARCHAR(1000), status SMALLINT NOT NULL DEFAULT 0,
 create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP, update_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP 
);
CREATE TABLE IF NOT EXISTS v_member_store (member_id BIGINT PRIMARY KEY, store_id BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS v_order_store (order_id BIGINT PRIMARY KEY, store_id BIGINT NOT NULL, name_snapshot VARCHAR(80), address_snapshot VARCHAR(300));
CREATE TABLE IF NOT EXISTS v_coupon_publication (publication_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, coupon_id BIGINT NOT NULL UNIQUE, enabled SMALLINT NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS v_friend_request (
 request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, sender_id BIGINT NOT NULL, receiver_id BIGINT NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'PENDING', note VARCHAR(200), create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS v_friend (member_id BIGINT NOT NULL, friend_id BIGINT NOT NULL, remark VARCHAR(50), PRIMARY KEY(member_id,friend_id));
CREATE TABLE IF NOT EXISTS v_social_block (member_id BIGINT NOT NULL, blocked_id BIGINT NOT NULL, PRIMARY KEY(member_id,blocked_id));
CREATE TABLE IF NOT EXISTS v_conversation (
 conversation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, kind VARCHAR(10) NOT NULL,
 name VARCHAR(80), owner_id BIGINT NOT NULL, private_key VARCHAR(50) UNIQUE,
 create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP, update_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP 
);
CREATE TABLE IF NOT EXISTS v_conversation_member (
 conversation_id BIGINT NOT NULL, member_id BIGINT NOT NULL, role VARCHAR(10) NOT NULL DEFAULT 'MEMBER',
 last_read_id BIGINT NOT NULL DEFAULT 0, joined_message_id BIGINT NOT NULL DEFAULT 0, PRIMARY KEY(conversation_id,member_id)
);
CREATE TABLE IF NOT EXISTS v_chat_message (
 message_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, conversation_id BIGINT NOT NULL, sender_id BIGINT NOT NULL,
 kind VARCHAR(10) NOT NULL, content VARCHAR(4000), product_id BIGINT, media_id VARCHAR(32),
 request_key VARCHAR(80) NOT NULL, create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS v_chat_media (
 media_id VARCHAR(32) PRIMARY KEY, conversation_id BIGINT NOT NULL, owner_id BIGINT NOT NULL,
 filename VARCHAR(40) NOT NULL, create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS v_social_event (
 event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, member_id BIGINT NOT NULL, payload TEXT NOT NULL,
 create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS v_social_call (
 call_id VARCHAR(32) PRIMARY KEY, conversation_id BIGINT NOT NULL, caller_id BIGINT NOT NULL, receiver_id BIGINT NOT NULL,
 media VARCHAR(10) NOT NULL, state VARCHAR(16) NOT NULL, create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 update_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP 
);
CREATE TABLE IF NOT EXISTS v_ai_usage (member_id BIGINT NOT NULL, usage_day DATE NOT NULL, requests INT NOT NULL DEFAULT 0, PRIMARY KEY(member_id,usage_day));
CREATE TABLE IF NOT EXISTS v_ai_history (
 entry_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, member_id BIGINT NOT NULL, question VARCHAR(2000) NOT NULL,
 answer TEXT NOT NULL, product_ids VARCHAR(1000), create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

